let current = 'ru';
export function setLang(l) {
  current = DICTS[l] ? l : 'ru';
  document.documentElement.lang = current;
}
export function lang() {
  return current;
}
export function t(key, vars) {
  let s = DICTS[current][key] ?? DICTS.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
const numFmt = {};
export function fmt(n) {
  const loc = current === 'en' ? 'en-US' : current === 'uk' ? 'uk-UA' : 'ru-RU';
  numFmt[loc] = numFmt[loc] || new Intl.NumberFormat(loc, { maximumFractionDigits: 2 });
  return numFmt[loc].format(n);
}
export function fmtDate(iso) {
  const loc = current === 'en' ? 'en-US' : current === 'uk' ? 'uk-UA' : 'ru-RU';
  return new Date(iso).toLocaleDateString(loc, { day: 'numeric', month: 'short', year: 'numeric' });
}
export function fmtDateTime(iso) {
  const loc = current === 'en' ? 'en-US' : current === 'uk' ? 'uk-UA' : 'ru-RU';
  return new Date(iso).toLocaleString(loc, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
}
